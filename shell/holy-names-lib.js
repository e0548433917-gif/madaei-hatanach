// נרמול: הסרת ניקוד וטעמים לצורך השוואה
const DIACRITICS_RE_GLOBAL = /[\u0591-\u05C7]/g;
const DIACRITICS_RE_SINGLE = /[\u0591-\u05C7]/;

function stripDiacritics(str) {
  // טווח יוניקוד של ניקוד עברי: \u05B0-\u05C7, טעמים: \u0591-\u05AF
  return str.replace(DIACRITICS_RE_GLOBAL, '');
}

function isDiacriticChar(ch) {
  return DIACRITICS_RE_SINGLE.test(ch);
}

// אות/ניקוד כיחידה אחת (לשימוש בבניית תבניות)
const DIA_CLASS = '[\u05B0-\u05C7\u0591-\u05AF]';

// אותיות תחילית עבריות מוכרות (ו,ב,כ,ל,מ,ש,ה) - "ו-החיבור", "ב/כ/ל/מ" השימוש, "ה" הידיעה/השאלה
const PREFIX_LETTERS = '\u05D5\u05D1\u05DB\u05DC\u05DE\u05E9\u05D4';

/**
 * בונה מקטע-רגקס (מחרוזת, להטמעה בתוך new RegExp / תבנית) שמתאים לגבול-מילה,
 * תוך התרה מפורשת של שרשרת קצרה (1-2) של אותיות תחילית עבריות שהיא עצמה
 * יושבת על גבול מילה אמיתי. ראו הערה למפתח למעלה בקובץ להסבר המלא ולמלכודת
 * שהטכניקה הזו נועדה למנוע (וגם למלכודת שכמעט נפלתי בה תוך כדי כתיבתה).
 * שימו לב: [^\u0591-\u05F4] ולא [^\u05D0-\u05EA] - צריך לחסום גם תווי ניקוד,
 * לא רק אותיות, כדי שהגבול יהיה גבול-מילה אמיתי ולא "עצר על תו ניקוד".
 */
function wordStartWithPrefix() {
  return `(?:(?<![\\u05D0-\\u05EA]${DIA_CLASS}*)|(?<=(?:^|[^\\u0591-\\u05F4])(?:[${PREFIX_LETTERS}]${DIA_CLASS}*){1,2}))`;
}

// אותיות תחילית ל-"יה" במצב *בלי ניקוד* בלבד (ראו PATTERN_NOTE_AGGRESSIVE למטה) - זהה ל-
// PREFIX_LETTERS אך *בלי ה'*. הסיבה: "ה" + "יה" בלי ניקוד שקול טקסטואלית למילה "היה" (=was),
// אחד הפעלים הנפוצים ביותר בעברית. עם ניקוד מלא זה מוגן ע"י דרישת הדגש/מפיק על ה-ה' הסופית
// (שלא קיים בפועל בפועל "היה"), אבל במצב בלי-ניקוד אין ניקוד שיגן על זה - ולכן חייבים להוציא
// את ה' מרשימת התחיליות המותרות עבור הענף הזה בלבד, אחרת "היה"/"והיה"/וכו' ייתפסו בטעות.
const PREFIX_LETTERS_NO_HE = '\u05D5\u05D1\u05DB\u05DC\u05DE\u05E9';
function wordStartWithPrefixNoHe() {
  return `(?:(?<![\\u05D0-\\u05EA]${DIA_CLASS}*)|(?<=(?:^|[^\\u0591-\\u05F4])(?:[${PREFIX_LETTERS_NO_HE}]${DIA_CLASS}*){1,2}))`;
}

