// מחרוזות exception מנורמלות (ללא ניקוד)
const EXCEPTIONS = EXCEPTIONS_STRIPPED.map(e => stripDiacritics(e));

/**
 * ⚠️ תוקן: מיפוי אינדקסים בין הטקסט המקורי (עם ניקוד אפשרי) לטקסט המנוקה מניקוד.
 * לפני התיקון, isException השווה אינדקסים של ההתאמה (שנמדדו על הטקסט המקורי, כולל ניקוד)
 * ישירות מול אינדקסים בתוך stripDiacritics(text) (טקסט קצר יותר) — בלי מיפוי בין השניים.
 * מכל תו ניקוד שמופיע *לפני* ההתאמה בטקסט כולו, האינדקסים זזים, וההשוואה יוצאת שגויה —
 * כלומר חריגים (למשל "בית אל") לא היו מזוהים כלל בטקסט עם ניקוד. תוקן ע"י מיפוי מפורש.
 */
function buildOriginalToStrippedMap(text) {
  const map = new Array(text.length + 1);
  let s = 0;
  for (let i = 0; i < text.length; i++) {
    map[i] = s;
    if (!isDiacriticChar(text[i])) s++;
  }
  map[text.length] = s;
  return map;
}

/**
 * בודק אם מיקום נתון (אינדקסים בטקסט המקורי) נמצא בתוך מילת exception.
 * originalToStrippedMap הוא המיפוי המתאים לטקסט הזה (ראו buildOriginalToStrippedMap).
 */
function isException(text, matchStart, matchEnd, originalToStrippedMap) {
  const stripped = stripDiacritics(text);
  const map = originalToStrippedMap || buildOriginalToStrippedMap(text);
  const sStart = map[matchStart];
  const sEnd = map[matchEnd];
  for (const exc of EXCEPTIONS) {
    let idx = stripped.indexOf(exc);
    while (idx !== -1) {
      const excEnd = idx + exc.length;
      if (sStart < excEnd && sEnd > idx) return true;
      idx = stripped.indexOf(exc, idx + 1);
    }
  }
  return false;
}

function namesForSettings(settings) {
  const { scope = 'all' } = settings;
  const enabled = settings.enabledNames || HOLY_NAMES.map(n => n.id);
  let names = scope === 'havaya' ? HOLY_NAMES.filter(n => n.id === 'havaya') : HOLY_NAMES;
  names = names.filter(n => enabled.includes(n.id));
  // ⚠️ נוסף ב-1.3.5: כמה שמות (כרגע 'el' ו-'yah') מגדירים pattern כפונקציה של settings
  // (למשל settings.aggressiveNoNikud) ולא כ-RegExp סטטי - ראו PATTERN_NOTE_AGGRESSIVE למעלה.
  // פותרים אותם כאן להתאמה קונקרטית, כך ששאר הקוד (findMatches וכו') ממשיך לעבוד עם RegExp
  // רגיל בלי לדעת שהיה כאן שלב ביניים.
  return names.map(n => (typeof n.pattern === 'function') ? { ...n, pattern: n.pattern(settings) } : n);
}

/**
 * מוצא את כל ההתאמות של שמות קדושים בטקסט נתון (ללא בדיקת exceptions),
 * תוך פתרון חפיפות (התאמה ארוכה יותר גוברת).
 */
function findMatches(searchText, names) {
  const raw = [];
  for (const name of names) {
    const regex = new RegExp(name.pattern.source, 'g');
    let m;
    while ((m = regex.exec(searchText)) !== null) {
      raw.push({ start: m.index, end: m.index + m[0].length, name });
      if (m[0].length === 0) regex.lastIndex++; // הגנה מפני לולאה אינסופית
    }
  }
  raw.sort((a, b) => a.start - b.start || (b.end - b.start) - (a.end - a.start));
  const filtered = [];
  let lastEnd = -1;
  for (const mm of raw) {
    if (mm.start >= lastEnd) { filtered.push(mm); lastEnd = mm.end; }
  }
  return filtered;
}

/**
 * ביצוע ההחלפה בטקסט רגיל (זיהוי ישיר על הטקסט המקורי — עם/בלי ניקוד קיים)
 * @param {string} text — הטקסט המקורי
 * @param {object} settings — { mode: 'hyphen'|'kinuy', scope: 'all'|'havaya', enabledNames: [...] }
 * @returns {{ result: string, count: number }}
 */
function replaceHolyNames(text, settings) {
  const { mode = 'hyphen' } = settings;
  const names = namesForSettings(settings);

  const o2s = buildOriginalToStrippedMap(text);
  const matches = findMatches(text, names).filter(
    mm => !isException(text, mm.start, mm.end, o2s)
  );

  let result = text;
  let count = 0;
  for (let i = matches.length - 1; i >= 0; i--) {
    const { start, end, name } = matches[i];
    const repl = resolveReplacement(name, mode, text.slice(start, end));
    result = result.slice(0, start) + repl + result.slice(end);
    count++;
  }
  return { result, count };
}

/**
 * מחזיר את מחרוזת ההחלפה לשם נתון. replacement_kinuy/replacement_hyphen יכולים להיות מחרוזת קבועה
 * או פונקציה (matchedText) => string, לשמות שההחלפה שלהם תלויה בכתיב המדויק שנמצא בטקסט (למשל
 * שימור כתיב מלא/חסר של "אלהים"/"אלוהים" בניקוי).
 */
function resolveReplacement(name, mode, matchedText, vocalizedMatchedText) {
  const repl = mode === 'hyphen' ? name.replacement_hyphen : name.replacement_kinuy;
  return typeof repl === 'function' ? repl(matchedText, vocalizedMatchedText) : repl;
}

/**
 * בונה מיפוי מכל אינדקס בטקסט המנוקד (ע"י בינה מלאכותית) לאינדקס המקביל
 * בטקסט המקורי (הלא מנוקד). מבוסס על ההנחה ש-stripDiacritics(vocalizedText) === originalText.
 */
function buildVocalizedToOriginalMap(vocalizedText) {
  const map = new Array(vocalizedText.length + 1);
  let orig = 0;
  for (let i = 0; i < vocalizedText.length; i++) {
    map[i] = orig;
    if (!isDiacriticChar(vocalizedText[i])) orig++;
  }
  map[vocalizedText.length] = orig;
  return map;
}

/**
 * זיהוי שמות קדושים על גבי טקסט שנוקד ע"י מנוע בינה מלאכותית מקומי,
 * תוך החלת ההחלפה על הטקסט המקורי בלבד (הניקוד משמש לזיהוי מדויק יותר,
 * אך אינו "נדבק" לשאר הטקסט הפלט).
 * @param {string} originalText — הטקסט המקורי (כפי שהוא בקובץ)
 * @param {string} vocalizedText — אותו טקסט לאחר ניקוד אוטומטי (אותם אותיות, בסדר זהה)
 * @param {object} settings
 * @returns {{ result: string, count: number }}
 */
function replaceHolyNamesWithVocalized(originalText, vocalizedText, settings) {
  const { mode = 'hyphen' } = settings;
  const names = namesForSettings(settings);

  const map = buildVocalizedToOriginalMap(vocalizedText);
  const rawMatches = findMatches(vocalizedText, names).map(mm => ({
    start: map[mm.start],
    end: map[mm.end],
    name: mm.name,
    // ⚠️ תוקן: שומרים את הקטע *המנוקד* של ההתאמה (כפי שהיא נמצאה בפועל ב-vocalizedText, לפני
    // המיפוי לאינדקסים של הטקסט המקורי). בלי זה, פונקציות replacement שתלויות בסימני ניקוד
    // ספציפיים בתוך ההתאמה (כמו ההבחנה "א-ל"/"א-לי" לפי חיריק) מקבלות רק את הקטע המקורי
    // הלא-מנוקד ותמיד "רואות" שאין ניקוד - מה שגרם למחיקת אותיות כינוי-גוף בפלט. ראו הערה
    // מפורטת ליד replacement_hyphen/kinuy של 'el' למעלה בקובץ.
    vocalizedMatch: vocalizedText.slice(mm.start, mm.end),
  }));

  // חפיפות עלולות להיווצר מחדש אחרי המיפוי (נדיר, אך ליתר ביטחון)
  rawMatches.sort((a, b) => a.start - b.start || (b.end - b.start) - (a.end - a.start));
  const matches = [];
  let lastEnd = -1;
  for (const mm of rawMatches) {
    if (mm.start >= lastEnd) { matches.push(mm); lastEnd = mm.end; }
  }

  const o2s = buildOriginalToStrippedMap(originalText);
  const filtered = matches.filter(mm => !isException(originalText, mm.start, mm.end, o2s));

  let result = originalText;
  let count = 0;
  for (let i = filtered.length - 1; i >= 0; i--) {
    const { start, end, name, vocalizedMatch } = filtered[i];
    const repl = resolveReplacement(name, mode, originalText.slice(start, end), vocalizedMatch);
    result = result.slice(0, start) + repl + result.slice(end);
    count++;
  }
  return { result, count };
}

