  // isException הוא substring גולמי בלי גבולות-מילה, ו"היה" הוא תת-מחרוזת מדויקת בתוך "אהיה" -
  // הוספתו הייתה חוסמת גם את הזיהוי של השם 'ehye' (אהיה), שמסומן תמיד בכוונה (ראו הערה למעלה
  // ליד 'ehye') ואסור להיחלש בלי לשוחח עם המשתמש קודם. אומת תכנותית: הוספת 'היה' גרמה
