#!/usr/bin/env python3
"""#78 — פיצול ״בהט, שש, דר וסוחרת״ (אסתר א, ו) לארבעה ערכים. כל דבר כאן נלקח מטקסט
שנשלף מספריא: בבלי מגילה יב ע״א, רש״י ואבן עזרא על אסתר א, ו. ״שיש טהור״ (שנוסף ב-#83)
מאוחד לתוך ״שש (אבן)״ — זה אותו חומר."""
import json
F = 'guides/domem/data/domem-data.js'
VERSE = {'ref': 'אסתר, א ו', 'text': 'חוּר כַּרְפַּס וּתְכֵלֶת אָחוּז בְּחַבְלֵי בוּץ וְאַרְגָּמָן עַל גְּלִילֵי כֶסֶף וְעַמּוּדֵי שֵׁשׁ מִטּוֹת זָהָב וָכֶסֶף עַל רִצְפַת בַּהַט וָשֵׁשׁ וְדַר וְסֹחָרֶת.'}
MEG = 'בבלי, מגילה יב ע"א'
RASHI = {'ref': 'רש״י, אסתר א ו', 'text': 'קַרְקָעוֹת שֶׁל בַּהַט וָשֵׁשׁ, וגו\'. מִינֵי אֲבָנִים טוֹבוֹת פֵּרְשׁוּ רַבּוֹתֵינוּ'}
IBN = {'ref': 'אבן עזרא, אסתר א ו', 'text': 'בהט. גם דר וסחרת אבנים יקרות'}
def entry(name, aliases, expl, ident, makorot):
    return {'name': name, 'cat': 'metals', 'img': None, 'aliases': aliases, 'tribe': None, 'explanation': expl,
            'identification': ident, 'note': 'אחד מארבעת חומרי הרצפה שבארמון אחשוורוש — ״בהט ושש ודר וסוחרת״ (אסתר א, ו).', 'gallery': [], 'makorot': makorot}
s = open(F, encoding='utf8').read(); i = s.index('const DATA = ') + 13
D, e = json.JSONDecoder().raw_decode(s, i)
old = next(d for d in D if d['name'] == 'בהט, שש, דר וסוחרת')
sheish_tahor = next((d for d in D if d['name'] == 'שיש טהור'), None)
extra = [m for m in old['makorot'] if m['ref'] != VERSE['ref']]
NEW = [
  entry('בהט', [], 'מחומרי הרצפה בארמון אחשוורוש. רבי אסי בגמרא דורש: ״אבנים שמתחוטטות על בעליהן״, ומביא ״אבני נזר מתנוססות על אדמתו״.',
        'מין אבן יקרה (רש״י: ״מיני אבנים טובות פירשו רבותינו״; אבן עזרא: ״אבנים יקרות״). זיהויה המדויק אינו ידוע.',
        [VERSE, {'ref': MEG, 'text': 'אמר רבי אסי: אבנים שמתחוטטות על בעליהן'}, RASHI, IBN]),
  entry('שש (אבן)', ['שיש', 'אבני שיש', 'שיש טהור', 'marble'], 'אבן השיש. אבן עזרא מפרש ״עמודי שש״ — ״כמו שיש״. בדברי הימים ״אבני שיש לרוב״ בין חומרי בניין המקדש, ובחז״ל ״אבני שיש טהור״. אינו ״שש״ של בגדי הכהונה (פשתן).',
        'שיש (Marble).',
        [VERSE, {'ref': 'אבן עזרא, אסתר א ו', 'text': 'ועמודי שש. כמו שיש'}] + extra + ([m for m in sheish_tahor['makorot'] if m['ref'] not in {x['ref'] for x in extra}] if sheish_tahor else [])),
  entry('דר', ['דרה'], 'מחומרי הרצפה בארמון אחשוורוש. בגמרא נחלקו: רב אמר ״דרי דרי״ — שורות שורות; ושמואל אמר שזו אבן טובה מכרכי הים ששמה ״דרה״, שהושיבה באמצע הסעודה והאירה להם כצהריים.',
        'לשמואל — אבן טובה מאירה בשם ״דרה״; לרב — אין זה שם אבן אלא ״שורות שורות״. אבן עזרא: אבן יקרה. זיהוי מודרני ודאי אין.',
        [VERSE, {'ref': MEG, 'text': 'אבן טובה יש בכרכי הים ודרה שמה'}, IBN]),
  entry('סוחרת', ['סחרת'], 'מחומרי הרצפה בארמון אחשוורוש. דבי רבי ישמעאל בגמרא דרשו: ״שקרא דרור לכל בעלי סחורה״ — מלשון סחורה.',
        'לפי הפשט (אבן עזרא) — אבן יקרה; לדבי רבי ישמעאל — דרשה מלשון סחורה ולא שם אבן. זיהוי מודרני ודאי אין.',
        [VERSE, {'ref': MEG, 'text': 'שקרא דרור לכל בעלי סחורה'}, IBN]),
]
out = []
for d in D:
    if d is old: out.extend(NEW); continue
    if d is sheish_tahor: continue
    out.append(d)
open(F, 'w', encoding='utf8').write(s[:i] + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + s[e:])
print('פוצל ל-4; ״שיש טהור״ אוחד:', bool(sheish_tahor), '· סה״כ', len(out))
