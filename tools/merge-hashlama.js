function readFile(rel) { return fs.readFileSync(path.join(ROOT, rel), 'utf8'); }
function safeWrite(rel, out, orig) {
  if (typeof out !== 'string' || out.length <= orig.length) throw new Error('הפלט קצר מהמקור או ריק — לא נכתב: ' + rel);
  fs.writeFileSync(path.join(ROOT, rel), out, 'utf8');
}
function nameIndex(data) {
  const idx = new Set();
  for (const d of data) for (const n of [d.name, ...(d.aliases || [])]) { const k = norm(n); if (k) idx.add(k); }
  return idx;
}
function filterNew(list, data, label) {
  const idx = nameIndex(data);
  const fresh = [], dup = [];
  for (const e of list) {
    const variants = [e.name, ...(e.aliases || [])].map(norm);
    if (variants.some((v) => idx.has(v))) dup.push(e.name); else fresh.push(e);
  }
  log(`  ${label}: ${fresh.length} חדשים` + (dup.length ? ` · ${dup.length} כבר קיימים ודולגו: ${dup.join(', ')}` : ''));
  return fresh;
}

