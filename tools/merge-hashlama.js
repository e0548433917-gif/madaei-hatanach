function runDomem() {
  log('\n=== דומם ===');
  const src = readFile(FILES.domem);
  const start = src.indexOf('const DATA = ') + 'const DATA = '.length;
  const end = src.indexOf('];', start) + 1;
  const raw = src.slice(start, end);
  const data = JSON.parse(raw);
  log('  ב-DATA כרגע: ' + data.length);

  const fresh = filterNew(DOMEM_NEW, data, 'ערכים חדשים');
  const cats = {};
  fresh.forEach((e) => { cats[e.cat] = (cats[e.cat] || 0) + 1; });
  log('  לפי קטגוריה: ' + JSON.stringify(cats));

  let enriched = 0;
  for (const en of DOMEM_ENRICH) {
    const d = data.find((x) => x.name === en.name);
    if (!d) { log('  ⚠️ לא נמצא להעשרה: ' + en.name); continue; }
    const before = JSON.stringify(d);
    if (en.addAliases) for (const a of en.addAliases) if (!(d.aliases || []).includes(a)) (d.aliases = d.aliases || []).push(a);
    if (en.replaceMakorot) d.makorot = en.replaceMakorot.slice();
    if (en.addMakorot) for (const m of en.addMakorot) if (!(d.makorot || []).some((x) => x.ref === m.ref)) (d.makorot = d.makorot || []).push(m);
    if (en.identification) d.identification = en.identification;
    if (en.note) d.note = en.note;
    if (en.appendNote) d.note = (d.note ? d.note + ' ' : '') + en.appendNote;
    if (JSON.stringify(d) !== before) { enriched++; log('  ✦ הועשר: ' + en.name); }
  }

  const next = data.concat(fresh);
  if (WRITE && (fresh.length || enriched)) {
    const out = src.slice(0, start) + JSON.stringify(next) + src.slice(end);
    safeWrite(FILES.domem, out, src);
    const check = loadDataFile(FILES.domem).DATA;
    if (check.length !== next.length) { fs.writeFileSync(path.join(ROOT, FILES.domem), src, 'utf8'); throw new Error('דומם: הטעינה מחדש לא תאמה — שוחזר המקור'); }
    log(`  ✅ נכתב: ${data.length} → ${check.length} (+${fresh.length}), ${enriched} העשרות`);
  }
  return { added: fresh.length, enriched };
}

