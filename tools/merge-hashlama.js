function main() {
  log(WRITE ? '🔧 מצב כתיבה' : '👁 ריצה יבשה (הוסף --write לשילוב בפועל)');
  const r = {
    domem: runDomem(),
    animal: runLiteral('animal', ANIMAL_NEW, 'בעלי חיים'),
    flora: runLiteral('flora', FLORA_NEW, 'צומח'),
    places: runLiteral('places', PLACES_NEW, 'מקומות'),
  };
  log('\n=== סיכום ===');
  for (const [k, v] of Object.entries(r)) log(`  ${k}: +${v.added} חדשים, ${v.enriched} העשרות`);
  if (!WRITE) log('\n(לא נכתב דבר)');
}

