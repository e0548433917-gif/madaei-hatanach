// object-literal (animal / flora / places)
// ---------------------------------------------------------------------------
function runLiteral(key, list, label) {
  log(`\n=== ${label} ===`);
  const rel = FILES[key];
  const src = readFile(rel);
  const data = loadDataFile(rel).DATA || [];
  log('  ב-DATA כרגע: ' + data.length);
  const fresh = filterNew(list, data, 'ערכים חדשים');

  let out = src;
  let enriched = 0;
  for (const en of LITERAL_ENRICH[key] || []) {
    const n = out.split(en.find).length - 1;
    if (n !== 1) { log(`  ⚠️ עוגן העשרה הופיע ${n} פעמים במקום 1 — דולג`); continue; }
    out = out.replace(en.find, () => en.replace);
    enriched++;
  }
  if (enriched) log(`  ✦ ${enriched} העשרות (עוגן ייחודי)`);

  if (fresh.length) {
    const dStart = out.indexOf('const DATA');
    const m = /\}\s*\];/.exec(out.slice(dStart));
    if (!m) throw new Error(label + ': לא נמצא סוף המערך');
    const closeAt = dStart + m.index + 1; // אחרי ה-} האחרון של הרשומה האחרונה
    const ins = ',\n' + fresh.map((e) => JSON.stringify(e)).join(',\n') + '\n';
    out = out.slice(0, closeAt) + ins + out.slice(closeAt);
  }

  if (WRITE && (fresh.length || enriched)) {
    safeWrite(rel, out, src);
    const check = loadDataFile(rel).DATA || [];
    if (check.length !== data.length + fresh.length) { fs.writeFileSync(path.join(ROOT, rel), src, 'utf8'); throw new Error(label + ': הטעינה מחדש לא תאמה — שוחזר המקור'); }
    log(`  ✅ נכתב: ${data.length} → ${check.length} (+${fresh.length}), ${enriched} העשרות`);
  }
  return { added: fresh.length, enriched };
}

